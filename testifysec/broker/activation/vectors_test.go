package activation

import (
	"encoding/json"
	"fmt"
	"os"
	"testing"
)

// The contract model's conformance vectors (testifysec/formal/contract, `lake exe
// contract-vectors`). CONTRACT_VECTORS overrides the path, as the formal step's replay sets it.
func contractVectors(t *testing.T) []byte {
	t.Helper()
	path := os.Getenv("CONTRACT_VECTORS")
	if path == "" {
		path = "../../formal/contract/vectors/contract-vectors.json"
	}
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("contract vectors: %v (they are generated by testifysec/formal/contract)", err)
	}
	return raw
}

type backendVector struct {
	Name, Pinned string
	HighWater    struct{ Activation, Profile, Reset uint64 }
	Artifact     struct {
		Kind, Tenant, Deployment, Profile, Device, SignedUnder string
		ProfileDigest, ProfileSequence, Sequence               int
		ResetSequence, ProfileFloor, ActivationFloor           int
		NotBefore, Expires, LeafNotBefore, LeafNotAfter        int64
		SignerIdentity, SignatureValid                         bool
	}
	Expect, Portal, Platform string
}

// Every `backends` case, with real certificates and signatures: two roots stand for the device's
// own backend and the other one, and each vector's abstract artifact becomes a signed record.
func TestContractVectorsBackends(t *testing.T) {
	var d struct {
		Schema            string
		Backends          []backendVector
		AdmissionSequence []struct {
			HighWater uint64
			Sequences []uint64
			Admitted  []uint64
		}
	}
	if err := json.Unmarshal(contractVectors(t), &d); err != nil {
		t.Fatal(err)
	}
	if d.Schema != "badger.contract.vectors/v1" || len(d.Backends) < 16 || len(d.AdmissionSequence) == 0 {
		t.Fatalf("unexpected vectors: schema %q, %d backend cases", d.Schema, len(d.Backends))
	}
	own, other := newRoot(t, "own backend"), newRoot(t, "other backend")
	for _, v := range d.Backends {
		t.Run(v.Name, func(t *testing.T) {
			if v.Portal != v.Expect || v.Platform != v.Expect {
				t.Fatalf("the backends disagree: %+v", v)
			}
			trust := trustFor(own)
			if v.Pinned == "both" {
				trust = trustFor(own, other)
			}
			a := v.Artifact
			s := signer{issuer: own, notBefore: a.LeafNotBefore, last: a.LeafNotAfter, san: portalSAN, corrupt: !a.SignatureValid}
			if a.SignedUnder == "other" {
				s.issuer = other
			}
			if !a.SignerIdentity {
				s.san = "spiffe://enclave.example/badger/someone-else"
			}
			pick := func(which, assigned, other string) string {
				return map[bool]string{true: assigned, false: other}[which == "assigned"]
			}
			body, kind := resetBody(7, a.ResetSequence, a.ProfileFloor, a.ActivationFloor, a.NotBefore, a.Expires), ResetType
			if a.Kind == "activation" {
				body, kind = activationBody(a.Sequence, a.ProfileSequence, a.ProfileDigest, a.NotBefore, a.Expires), ActivationType
				body["profileId"] = pick(a.Profile, "engineering", "finance")
			} else {
				body["deviceKeySpkiSha256"] = pick(a.Device, digestOf(7), digestOf(9))
			}
			body["tenantId"], body["deploymentId"] = pick(a.Tenant, "tenant-a", "tenant-b"), pick(a.Deployment, "deploy-a", "deploy-b")
			raw := envelope(t, kind, body, s)
			before := State{ProfileHighWater: v.HighWater.Profile, ActivationHighWater: v.HighWater.Activation,
				ResetHighWater: v.HighWater.Reset, ProfileSHA256: digestOf(100)}
			after, got := apply(trust, before, raw)
			if got != v.Expect {
				t.Fatalf("got %s, the model says %s", got, v.Expect)
			}
			want := before
			switch {
			case got != "ok":
			case a.Kind == "activation":
				want = State{uint64(a.ProfileSequence), uint64(a.Sequence), before.ResetHighWater, digestOf(a.ProfileDigest)}
			default:
				want = State{uint64(a.ProfileFloor), uint64(a.ActivationFloor), uint64(a.ResetSequence), before.ProfileSHA256}
			}
			if after != want {
				t.Fatalf("state %+v, the model's %+v", after, want)
			}
		})
	}
	for _, v := range d.AdmissionSequence {
		s, admitted := State{ProfileHighWater: v.HighWater}, []uint64{}
		for _, seq := range v.Sequences {
			if next, err := AdmitProfile(s, seq); err == nil {
				s, admitted = next, append(admitted, seq)
			}
		}
		if fmt.Sprint(admitted) != fmt.Sprint(v.Admitted) {
			t.Fatalf("high-water %d over %v admitted %v, the model %v", v.HighWater, v.Sequences, admitted, v.Admitted)
		}
	}
}
